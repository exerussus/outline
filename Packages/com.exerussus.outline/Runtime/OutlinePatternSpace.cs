namespace Exerussus.Outline
{
    /// <summary>В каком пространстве строится паттерн стиля.</summary>
    public enum OutlinePatternSpace
    {
        /// <summary>Экран: период в пикселях, паттерн неподвижен относительно кадра.</summary>
        Screen = 0,
        /// <summary>
        /// Объект: экранный паттерн, привязанный к центру объекта, с периодом в мировых единицах. Следует за
        /// перемещением объекта, приближением камеры и поворотом объекта вокруг оси взгляда.
        /// </summary>
        Object = 1,
        /// <summary>
        /// Поверхность в координатах объекта: паттерн нанесён на поверхность (проекция по доминирующей оси
        /// нормали) и поворачивается вместе с объектом. Свечение снаружи силуэта — как в режиме Object.
        /// </summary>
        SurfaceObject = 2,
        /// <summary>Поверхность в мировых координатах: паттерн неподвижен в мире, объект «проезжает» сквозь него.</summary>
        SurfaceWorld = 3,
    }
}
